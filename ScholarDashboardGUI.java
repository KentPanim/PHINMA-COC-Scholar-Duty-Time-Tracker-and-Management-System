    private void btnTimeInActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTimeInActionPerformed
  
   
    String findAssignmentSql =
        "SELECT a.assignment_id, ds.schedule_id, " +
        "ds.schedule_type, ds.start_time, ds.end_time " +
        "FROM scholars s " +
        "JOIN assignments a ON s.scholar_id = a.scholar_id " +
        "LEFT JOIN duty_schedules ds ON a.assignment_id = ds.assignment_id " +
        "WHERE s.student_id = ? " +
        "AND a.status = 'Active' " +
        "AND (ds.schedule_type = 'Flexible' " +
        "OR (ds.schedule_type = 'Fixed' " +
        "AND ds.day_of_week = DAYNAME(CURDATE()) " +
        "AND (ds.schedule_date IS NULL OR ds.schedule_date = CURDATE()) " +
        "AND CURTIME() BETWEEN ds.start_time AND ds.end_time)) " +
        "LIMIT 1";

    try (java.sql.Connection conn =
             scholarduty.DatabaseConnection.getConnection();
         java.sql.PreparedStatement pst =
             conn.prepareStatement(findAssignmentSql)) {

        pst.setString(1, loginId);

        try (java.sql.ResultSet rs = pst.executeQuery()) {
            if (!rs.next()) {
                javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "No eligible schedule found for Time In."
                );
                return;
            }

            int assignmentId = rs.getInt("assignment_id");
            int scheduleId = rs.getInt("schedule_id");
            boolean noScheduleId = rs.wasNull();

            String checkSql =
                "SELECT record_id FROM duty_records " +
                "WHERE assignment_id = ? " +
                "AND time_in IS NOT NULL " +
                "AND time_out IS NULL " +
                "LIMIT 1";

            try (java.sql.PreparedStatement checkPst =
                     conn.prepareStatement(checkSql)) {
                checkPst.setInt(1, assignmentId);

                try (java.sql.ResultSet checkRs =
                         checkPst.executeQuery()) {
                    if (checkRs.next()) {
                        javax.swing.JOptionPane.showMessageDialog(
                            this,
                            "You already have an active duty session. " +
                            "Please Time Out first."
                        );
                        return;
                    }
                }
            }

            String insertSql =
                "INSERT INTO duty_records " +
                "(assignment_id, schedule_id, duty_date, time_in, " +
                "attendance_status, verification_status) " +
                "VALUES (?, ?, CURDATE(), CURTIME(), 'Present', 'Pending')";

            try (java.sql.PreparedStatement insertPst =
                     conn.prepareStatement(insertSql)) {
                insertPst.setInt(1, assignmentId);

                if (noScheduleId) {
                    insertPst.setNull(2, java.sql.Types.INTEGER);
                } else {
                    insertPst.setInt(2, scheduleId);
                }

                insertPst.executeUpdate();

                javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Time In saved successfully!"
                );
            }
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Error saving Time In: " + e.getMessage()
        );
    }


    }//GEN-LAST:event_btnTimeInActionPerformed

    private void btnTimeOutActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTimeOutActionPerformed

    String sql =
        "SELECT record_id, time_in FROM duty_records " +
        "WHERE assignment_id = ? " +
        "AND duty_date = CURDATE() " +
        "AND time_out IS NULL " +
        "ORDER BY record_id DESC LIMIT 1";

    try (java.sql.Connection conn =
             scholarduty.DatabaseConnection.getConnection()) {

        // Find today's active duty record for this scholar
        String findSql =
            "SELECT d.record_id, d.time_in " +
            "FROM duty_records d " +
            "JOIN assignments a ON d.assignment_id = a.assignment_id " +
            "JOIN scholars s ON a.scholar_id = s.scholar_id " +
            "WHERE s.student_id = ? " +
            "AND d.duty_date = CURDATE() " +
            "AND d.time_out IS NULL " +
            "ORDER BY d.record_id DESC LIMIT 1";

        try (java.sql.PreparedStatement pst =
                 conn.prepareStatement(findSql)) {

            pst.setString(1, loginId);

            try (java.sql.ResultSet rs = pst.executeQuery()) {
                if (!rs.next()) {
                    javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "No active Time In record found for today."
                    );
                    return;
                }

                int recordId = rs.getInt("record_id");

                String updateSql =
                    "UPDATE duty_records SET " +
                    "time_out = CURTIME(), " +
                    "daily_hours = ROUND(TIME_TO_SEC(" +
                    "TIMEDIFF(CURTIME(), time_in)) / 3600, 2), " +
                    "attendance_status = 'Present' " +
                    "WHERE record_id = ? AND time_out IS NULL";

                try (java.sql.PreparedStatement updatePst =
                         conn.prepareStatement(updateSql)) {

                    updatePst.setInt(1, recordId);
                    int updated = updatePst.executeUpdate();

                    if (updated > 0) {
                        javax.swing.JOptionPane.showMessageDialog(
                            this,
                            "Time Out saved successfully!"
                        );
                    } else {
                        javax.swing.JOptionPane.showMessageDialog(
                            this,
                            "Time Out was not saved. Please try again."
                        );
                    }
                }
            }
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Error saving Time Out: " + e.getMessage()
        );
    }

    
    }//GEN-LAST:event_btnTimeOutActionPerformed

