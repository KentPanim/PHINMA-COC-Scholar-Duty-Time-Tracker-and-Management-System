       private void loadScholarProfile() {
    String sql =
        "SELECT s.student_id, s.first_name, s.last_name, " +
        "s.middle_initial, s.email, s.course, s.program, " +
        "o.office_name, " +
        "st.first_name AS staff_first_name, " +
        "st.last_name AS staff_last_name " +
        "FROM scholars s " +
        "LEFT JOIN assignments a " +
        "ON s.scholar_id = a.scholar_id " +
        "AND a.status = 'Active' " +
        "LEFT JOIN offices o ON a.office_id = o.office_id " +
        "LEFT JOIN staff st ON a.staff_id = st.staff_id " +
        "WHERE s.student_id = ?";

    try (java.sql.Connection conn =
             scholarduty.DatabaseConnection.getConnection();
         java.sql.PreparedStatement pst =
             conn.prepareStatement(sql)) {

        pst.setString(1, loginId);

        try (java.sql.ResultSet rs = pst.executeQuery()) {
            if (rs.next()) {

                // MY PROFILE
                lblStudentsId.setText(
                    rs.getString("student_id"));
                
                lblStudentId.setText(
                    rs.getString("student_id"));
                
                lblName.setText(
                    rs.getString("last_name") + ", " + 
                    rs.getString("first_name"));
                
                
                lblLastName.setText(
                    rs.getString("last_name"));

                lblFirstName.setText(
                    rs.getString("first_name"));

                String middleInitial =
                    rs.getString("middle_initial");

                lblMiddleInitial.setText(
                    middleInitial == null ? "" : middleInitial);

                lblEmail.setText(
                    rs.getString("email"));

                lblCourse.setText(
                    rs.getString("course"));

                lblProgram.setText(
                    rs.getString("program"));
                
                lblPrograms.setText(
                    rs.getString("program"));

                String office =
                    rs.getString("office_name");

                lblAssignedOffice.setText(
                    office == null ? "Not assigned" : office);

                String staffFirst =
                    rs.getString("staff_first_name");

                String staffLast =
                    rs.getString("staff_last_name");

                String staffName =
                    (staffFirst == null ? "" : staffFirst) +
                    (staffLast == null ? "" : " " + staffLast);

                lblAssignedStaff.setText(
                    staffName.trim().isEmpty()
                        ? "Not assigned"
                        : staffName.trim());
                
                String statusSql =
    "SELECT status FROM assignments " +
    "WHERE scholar_id = " +
    "(SELECT scholar_id FROM scholars WHERE student_id = ?) " +
    "ORDER BY assignment_id DESC LIMIT 1";

try (java.sql.PreparedStatement statusPst =
         conn.prepareStatement(statusSql)) {

    statusPst.setString(1, loginId);

    try (java.sql.ResultSet statusRs =
             statusPst.executeQuery()) {

        if (statusRs.next()) {
            lblStatus.setText(
                statusRs.getString("status"));
        } else {
            lblStatus.setText("Not Assigned");
        }
    }
}
            }
        }

        // LOAD DUTY HOURS
        loadScholarHours();

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Error loading scholar profile: " + e.getMessage()
        );
    }
}

