    private void loadDutyRecords() {
    javax.swing.table.DefaultTableModel model =
        (javax.swing.table.DefaultTableModel)
        tblDutyRecords.getModel();

    model.setRowCount(0);

    String sql =
        "SELECT d.duty_date, d.time_in, d.time_out, " +
        "d.daily_hours, d.attendance_status, " +
        "d.verification_status " +
        "FROM duty_records d " +
        "JOIN assignments a ON d.assignment_id = a.assignment_id " +
        "JOIN scholars s ON a.scholar_id = s.scholar_id " +
        "WHERE s.student_id = ? " +
        "ORDER BY d.duty_date DESC, d.record_id DESC";

    try (java.sql.Connection conn =
             scholarduty.DatabaseConnection.getConnection();
         java.sql.PreparedStatement pst =
             conn.prepareStatement(sql)) {

        pst.setString(1, loginId);

        try (java.sql.ResultSet rs = pst.executeQuery()) {
            while (rs.next()) {
                model.addRow(new Object[] {
                    rs.getDate("duty_date"),
                    rs.getTime("time_in"),
                    rs.getTime("time_out"),
                    rs.getObject("daily_hours"),
                    rs.getString("attendance_status"),
                    rs.getString("verification_status")
                });
            }
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Error loading duty records: " + e.getMessage()
        );
    }
    
    
    
    
}
private void loadMySchedule() {
    javax.swing.table.DefaultTableModel model =
        (javax.swing.table.DefaultTableModel)
        tblMySchedule.getModel();

    model.setRowCount(0);

    String sql =
    "SELECT ds.day_of_week, ds.schedule_date, " +
    "ds.schedule_type, ds.start_time, ds.end_time, " +
    "o.office_name, st.first_name, st.last_name " +
    "FROM scholars s " +
    "JOIN assignments a ON s.scholar_id = a.scholar_id " +
    "JOIN duty_schedules ds ON a.assignment_id = ds.assignment_id " +
    "LEFT JOIN offices o ON a.office_id = o.office_id " +
    "LEFT JOIN staff st ON a.staff_id = st.staff_id " +
    "WHERE s.student_id = ? " +
    "AND a.status = 'Active' " +
    "ORDER BY ds.day_of_week, ds.schedule_date";

    try (java.sql.Connection conn =
             scholarduty.DatabaseConnection.getConnection();
         java.sql.PreparedStatement pst =
             conn.prepareStatement(sql)) {

        pst.setString(1, loginId);

        try (java.sql.ResultSet rs = pst.executeQuery()) {
            while (rs.next()) {
                String dayDate;

                if ("Flexible".equalsIgnoreCase(
                        rs.getString("schedule_type"))) {
                    dayDate = "Any Day";
                } else if (rs.getDate("schedule_date") != null) {
                    dayDate = rs.getDate("schedule_date").toString();
                } else {
                    dayDate = rs.getString("day_of_week");
                }

                model.addRow(new Object[] {
                    dayDate,
                    rs.getString("schedule_type"),
                   formatScheduleTime(rs.getTime("start_time")),
                    formatScheduleTime(rs.getTime("end_time")),
                    rs.getString("office_name"),
                    rs.getString("first_name") + "" +
                        rs.getString("last_name")
                });
            }
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Error loading schedule: " + e.getMessage()
        );
    }
}


private String formatScheduleTime(java.sql.Time time) {
    if (time == null) {
        return "Any time";
    }

    java.text.SimpleDateFormat formatter =
        new java.text.SimpleDateFormat("h:mm a");

    return formatter.format(time);
}

private void loadScholarHours() {
    String sql =
        "SELECT a.assigned_hours, " +
        "COALESCE(SUM(d.daily_hours), 0) AS completed_hours " +
        "FROM scholars s " +
        "JOIN assignments a ON s.scholar_id = a.scholar_id " +
        "LEFT JOIN duty_records d " +
        "ON a.assignment_id = d.assignment_id " +
        "WHERE s.student_id = ? " +
        "AND a.status = 'Active' " +
        "GROUP BY a.assignment_id, a.assigned_hours";

    try (java.sql.Connection conn =
             scholarduty.DatabaseConnection.getConnection();
         java.sql.PreparedStatement pst =
             conn.prepareStatement(sql)) {

        pst.setString(1, loginId);

        try (java.sql.ResultSet rs = pst.executeQuery()) {
            if (rs.next()) {
                double assigned =
                    rs.getDouble("assigned_hours");

                double completed =
                    rs.getDouble("completed_hours");

                double remaining =
                    Math.max(0, assigned - completed);

                lblAssignedHours.setText(
                    String.valueOf(assigned));

                lblCompletedHours.setText(
                    String.valueOf(completed));

                lblRemainingHours.setText(
                    String.valueOf(remaining));
            }
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Error loading duty hours: " + e.getMessage()
        );
    }
}





