    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
  String loginId = txtLoginId.getText().trim();
String password = new String(txtPassword.getPassword());

if (loginId.isEmpty() || password.isEmpty()) {
    JOptionPane.showMessageDialog(
        this,
        "Please enter your ID and password."
    );
    return;
}

String sql = "SELECT role FROM users WHERE login_id = ? AND password = ?";

try (
    Connection conn = DatabaseConnection.getConnection();
    PreparedStatement pst = conn.prepareStatement(sql)
) {

    pst.setString(1, loginId);
    pst.setString(2, password);

    ResultSet rs = pst.executeQuery();

   if (rs.next()) {

    String role = rs.getString("role");

    if (role.equals("Admin")) {

        AdminDashboardGUI dashboard =
                new AdminDashboardGUI();

        dashboard.setVisible(true);
        this.dispose();
        
        } else if (role.equals("Scholar")) {

            
    ScholarDashboardGUI dashboard =
            new ScholarDashboardGUI(txtLoginId.getText().trim());

    dashboard.setVisible(true);
    this.dispose();

        } else if (role.equalsIgnoreCase("Staff")) {

    try {
        StaffDashboard dashboard = new StaffDashboard(txtLoginId.getText().trim());
        dashboard.setDefaultCloseOperation(javax.swing.JFrame.DISPOSE_ON_CLOSE);
        dashboard.setLocationRelativeTo(null);
        dashboard.setVisible(true);
        dashboard.toFront();
        dashboard.requestFocus();

        this.dispose();

    } catch (Exception e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(
            this,
            "Error opening Staff Dashboard: " + e.getMessage()
        );
    }


    } else {

        JOptionPane.showMessageDialog(
            this,
            "Login successful!\nRole: " + role
        );
   }
    } else {

        JOptionPane.showMessageDialog(
            this,
            "Invalid ID or password.",
            "Login Failed",
            JOptionPane.ERROR_MESSAGE
        );
    }

} catch (SQLException e) {

    JOptionPane.showMessageDialog(
        this,
        "Database error: " + e.getMessage(),
        "Error",
        JOptionPane.ERROR_MESSAGE
    );
}
    }//GEN-LAST:event_btnLoginActionPerformed

