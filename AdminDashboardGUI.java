    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed

     String studentId = txtStudentId.getText().trim();
    String lastName = txtLastName.getText().trim();
    String firstName = txtFirstName.getText().trim();
    String middleInitial = txtMiddleInitial.getText().trim();
    String email = txtEmail.getText().trim();

    String course = cmbCourse.getSelectedItem() != null
            ? cmbCourse.getSelectedItem().toString()
            : "";

    String program = cmbScholarProgram.getSelectedItem() != null
            ? cmbScholarProgram.getSelectedItem().toString()
            : "";

    
    if (studentId.isEmpty()
            || lastName.isEmpty()
            || firstName.isEmpty()
            || email.isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Please fill all required fields.",
                "Missing Information",
                JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    
    if (scholarService.studentIdExists(studentId)) {

        JOptionPane.showMessageDialog(
                this,
                "Student ID already exists.",
                "Duplicate Student ID",
                JOptionPane.WARNING_MESSAGE
        );

        return;
    }

  
    Scholar scholar = new Scholar(
            0,
            studentId,
            lastName,
            firstName,
            middleInitial,
            email,
            course,
            program
    );

   
    if (scholarService.addScholar(scholar)) {

        JOptionPane.showMessageDialog(
                this,
                "Scholar added successfully!\n\n"
                + "Login ID: " + studentId + "\n"
                + "Temporary Password: " + studentId
                + "\n\nRole: Scholar",
                "Scholar Account Created",
                JOptionPane.INFORMATION_MESSAGE
        );

      
        loadScholars();

       
        txtStudentId.setText("");
        txtLastName.setText("");
        txtFirstName.setText("");
        txtMiddleInitial.setText("");
        txtEmail.setText("");

        if (cmbCourse.getItemCount() > 0) {
            cmbCourse.setSelectedIndex(0);
        }

        if (cmbScholarProgram.getItemCount() > 0) {
            cmbScholarProgram.setSelectedIndex(0);
        }

    } else {

        JOptionPane.showMessageDialog(
                this,
                "Failed to add scholar.",
                "Error",
                JOptionPane.ERROR_MESSAGE
        );
    }


    }//GEN-LAST:event_btnAddActionPerformed

