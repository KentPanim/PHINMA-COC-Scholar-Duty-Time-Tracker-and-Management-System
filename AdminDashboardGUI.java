    private void btnAddAssignmentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddAssignmentActionPerformed

String staffText = cmbAssignmentStaff.getSelectedItem().toString();
String officeName = cmbAssignmentOffice.getSelectedItem().toString();

String assignedHoursText = txtAssignedHours.getText().trim();
String startDate = txtStartDate.getText().trim();
String endDate = txtEndDate.getText().trim();
String status = cmbAssignmentStatus.getSelectedItem().toString();

if (assignedHoursText.isEmpty()
        || startDate.isEmpty()
        || endDate.isEmpty()) {

    JOptionPane.showMessageDialog(
        this,
        "Please fill all required fields."
    );
    return;
}


String staffCode = staffText.split(" - ")[0];

int scholarId = selectedScholarId;
int staffId = 0;
int officeId = 0;

if (scholarId == 0) {
    JOptionPane.showMessageDialog(this,
            "Please search and select a valid scholar first.",
            "Scholar Required",
            JOptionPane.WARNING_MESSAGE);
    return;
}

java.util.List<scholarduty.Scholar> scholars =
        scholarService.findAllScholars();



java.util.List<scholarduty.Staff> staffList =
        staffService.findAllStaff();

for (scholarduty.Staff staff : staffList) {
    if (staff.getStaffCode().equals(staffCode)) {
        staffId = staff.getStaffId();
        break;
    }
}

java.util.List<scholarduty.Office> officeList =
        officeService.findAllOffices();

for (scholarduty.Office office : officeList) {
    if (office.getOfficeName().equals(officeName)) {
        officeId = office.getOfficeId();
        break;
    }
}
if (scholarId == 0 || staffId == 0 || officeId == 0) {

    JOptionPane.showMessageDialog(
        this,
        "Invalid Scholar, Staff, or Office selection.",
        "Assignment Error",
        JOptionPane.ERROR_MESSAGE
    );

    return;
}
int assignedHours;

try {
    assignedHours = Integer.parseInt(assignedHoursText);

    if (assignedHours <= 0) {
        JOptionPane.showMessageDialog(
            this,
            "Assigned hours must be greater than 0."
        );
        return;
    }

} catch (NumberFormatException e) {

    JOptionPane.showMessageDialog(
        this,
        "Assigned hours must be a valid number."
    );

    return;
}
if (assignmentService.addAssignment(
        scholarId,
        staffId,
        officeId,
        assignedHours,
        startDate,
        endDate,
        status)) {

    JOptionPane.showMessageDialog(
        this,
        "Assignment added successfully."
    );

    loadAssignments();

} else {

    JOptionPane.showMessageDialog(
        this,
        "Failed to add assignment.",
        "Assignment Error",
        JOptionPane.ERROR_MESSAGE
    );
}
    }//GEN-LAST:event_btnAddAssignmentActionPerformed

    private void btnSearchScholarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchScholarActionPerformed
     String search = txtSearchScholar.getText().trim();

if (search.isEmpty()) {
    JOptionPane.showMessageDialog(this,
            "Please enter Student ID or Scholar Name.");
    return;
}

selectedScholarId = 0;

List<Scholar> scholars = scholarService.findAllScholars();

for (Scholar scholar : scholars) {

    String fullName = scholar.getFirstName() + " "
            + scholar.getLastName();

    if (scholar.getStudentId().equalsIgnoreCase(search)
            || fullName.equalsIgnoreCase(search)
            || fullName.toLowerCase().contains(search.toLowerCase())) {

        selectedScholarId = scholar.getScholarId();

        JOptionPane.showMessageDialog(this,
                "Scholar found:\n"
                + scholar.getStudentId() + " - "
                + fullName);

        return;
    }
}

JOptionPane.showMessageDialog(this,
        "Scholar not found.",
        "Search Result",
        JOptionPane.WARNING_MESSAGE);
    }//GEN-LAST:event_btnSearchScholarActionPerformed

    private void btnAddScheduleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddScheduleActionPerformed
  if (selectedScheduleScholarId == 0) {
    JOptionPane.showMessageDialog(this,
            "Please search for a scholar first.",
            "Scholar Required",
            JOptionPane.WARNING_MESSAGE);
    return;
}

int assignmentId =
        assignmentService.findActiveAssignmentIdByScholarId(
                selectedScheduleScholarId);

if (assignmentId == 0) {
    JOptionPane.showMessageDialog(this,
            "No active assignment found for this scholar.",
            "Assignment Required",
            JOptionPane.WARNING_MESSAGE);
    return;
}

String scheduleType =
        cmbScheduleType.getSelectedItem().toString();

String dayOrDate =
        txtScheduleDate.getText().trim();

String startTime =
        txtStartTime.getText().trim();

String endTime =
        txtEndTime.getText().trim();


if (scheduleType.equalsIgnoreCase("Fixed")) {

    if (dayOrDate.isEmpty()
            || startTime.isEmpty()
            || endTime.isEmpty()) {

        JOptionPane.showMessageDialog(this,
                "Please complete Day/Date, Start Time, and End Time for Fixed schedule.",
                "Missing Information",
                JOptionPane.WARNING_MESSAGE);
        return;
    }

}


if (scheduleType.equalsIgnoreCase("Flexible")) {

    if (dayOrDate.isEmpty()) {
        dayOrDate = null;
    }

    if (startTime.isEmpty()) {
        startTime = null;
    }

    if (endTime.isEmpty()) {
        endTime = null;
    }
}


if (dutyScheduleService.addSchedule(
        assignmentId,
        dayOrDate,
        scheduleType,
        startTime,
        endTime)) {

    JOptionPane.showMessageDialog(this,
            "Duty schedule added successfully.");

    loadDutySchedules();

} else {

    JOptionPane.showMessageDialog(this,
            "Failed to add duty schedule.",
            "Schedule Error",
            JOptionPane.ERROR_MESSAGE);
}
        

  
    }//GEN-LAST:event_btnAddScheduleActionPerformed

